import AppKit
import Defaults
import UniformTypeIdentifiers

private struct ClipCaptureRequest: Sendable {
    let source: String?
    let captureText: Bool
    let captureLinks: Bool
    let captureImages: Bool
    let text: String?
    let imageData: Data?
    let fileURLs: [URL]
}

@MainActor
final class ClipboardMonitor {
    static let shared = ClipboardMonitor()

    static let pollInterval: TimeInterval = 0.5
    static let pollTolerance: TimeInterval = 0.25
    static let idlePollInterval: TimeInterval = 2
    static let idlePollTolerance: TimeInterval = 0.5
    static let idleThreshold: TimeInterval = 30
    private static let anyInputEvent = CGEventType(rawValue: ~0)

    static let skippedTypes: Set<NSPasteboard.PasteboardType> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
        "net.antelle.keeweb"
    ].reduce(into: []) { $0.insert(NSPasteboard.PasteboardType($1)) }

    static let sourceType = NSPasteboard.PasteboardType("org.nspasteboard.source")

    private nonisolated static let captureQueue = DispatchQueue(label: "dev.nubrix.vitrin.capture", qos: .utility)

    private var timer: Timer?
    private var idleCadence = false
    private var lastChangeCount: Int?
    private var wanted = false
    private var screensAsleep = false
    private var sessionInactive = false
    private var screenLocked = false
    private var observers: [(center: NotificationCenter, token: NSObjectProtocol)] = []

    private init() {}

    var isRunning: Bool { timer != nil }

    func start() {
        wanted = true
        registerObservers()
        updatePolling()
    }

    func stop() {
        wanted = false
        removeObservers()
        screensAsleep = false
        sessionInactive = false
        screenLocked = false
        updatePolling()
    }

    func acknowledge(changeCount: Int) {
        lastChangeCount = changeCount
    }

    private var shouldPoll: Bool {
        wanted && !screensAsleep && !sessionInactive && !screenLocked
    }

    private func updatePolling() {
        if shouldPoll {
            guard timer == nil else { return }
            lastChangeCount = NSPasteboard.general.changeCount
            scheduleTimer(idle: false)
        } else {
            timer?.invalidate()
            timer = nil
            idleCadence = false
            lastChangeCount = nil
        }
    }

    private func scheduleTimer(idle: Bool) {
        timer?.invalidate()
        idleCadence = idle
        let timer = Timer(timeInterval: idle ? Self.idlePollInterval : Self.pollInterval, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.tick() }
        }
        timer.tolerance = idle ? Self.idlePollTolerance : Self.pollTolerance
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    private func adaptCadence() {
        guard let anyInput = Self.anyInputEvent else { return }
        let idle = CGEventSource.secondsSinceLastEventType(.combinedSessionState, eventType: anyInput) > Self.idleThreshold
        if idle != idleCadence { scheduleTimer(idle: idle) }
    }

    private func registerObservers() {
        guard observers.isEmpty else { return }
        let workspace = NSWorkspace.shared.notificationCenter
        let distributed = DistributedNotificationCenter.default()
        func watch(_ center: NotificationCenter, _ name: Notification.Name, _ change: @escaping @MainActor @Sendable (ClipboardMonitor) -> Void) {
            let token = center.addObserver(forName: name, object: nil, queue: .main) { [weak self] _ in
                MainActor.assumeIsolated { if let self { change(self); self.updatePolling() } }
            }
            observers.append((center, token))
        }
        watch(workspace, NSWorkspace.screensDidSleepNotification) { $0.screensAsleep = true }
        watch(workspace, NSWorkspace.screensDidWakeNotification) { $0.screensAsleep = false }
        watch(workspace, NSWorkspace.sessionDidResignActiveNotification) { $0.sessionInactive = true }
        watch(workspace, NSWorkspace.sessionDidBecomeActiveNotification) { $0.sessionInactive = false }
        watch(distributed, Notification.Name("com.apple.screenIsLocked")) { $0.screenLocked = true }
        watch(distributed, Notification.Name("com.apple.screenIsUnlocked")) { $0.screenLocked = false }
    }

    private func removeObservers() {
        for observer in observers { observer.center.removeObserver(observer.token) }
        observers.removeAll()
    }

    private func tick() {
        adaptCadence()
        let pb = NSPasteboard.general
        let count = pb.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        guard Defaults[.vitrinEnabled], ClipStore.shared.isReady else { return }
        if #available(macOS 15.4, *) {
            if pb.accessBehavior == .alwaysDeny { return }
        }
        let types = Set(pb.types ?? [])
        guard !types.contains(ClipStore.ownPasteboardType),
              types.isDisjoint(with: Self.skippedTypes) else { return }
        let excluded = Defaults[.vitrinExcludedApps]
        let frontmost = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        var declared: String?
        if types.contains(Self.sourceType), let value = pb.string(forType: Self.sourceType)?.trimmingCharacters(in: .whitespacesAndNewlines), !value.isEmpty, value.utf8.count <= 256 {
            declared = value
        }
        let source = declared ?? frontmost
        if let frontmost, excluded.contains(frontmost) { return }
        if let declared, excluded.contains(declared) { return }
        let captureText = Defaults[.vitrinCaptureText]
        let captureLinks = Defaults[.vitrinCaptureLinks]
        let captureImages = Defaults[.vitrinCaptureImages]
        let hasFile = types.contains(.fileURL)
        let readsText = (captureText || captureLinks) && !hasFile
        let readsImage = captureImages && !hasFile && (types.contains(.png) || types.contains(.tiff))
        let readsFiles = captureImages && hasFile
        guard readsText || readsImage || readsFiles else { return }
        let fileURLs: [URL] = readsFiles
            ? (pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL] ?? [])
            : []
        let text = readsText ? pb.string(forType: .string) : nil
        var imageData: Data?
        if readsImage {
            for type in [NSPasteboard.PasteboardType.png, .tiff] where types.contains(type) {
                imageData = pb.data(forType: type)
                break
            }
        }
        guard pb.changeCount == count else { return }
        let request = ClipCaptureRequest(
            source: source,
            captureText: captureText,
            captureLinks: captureLinks,
            captureImages: captureImages,
            text: text,
            imageData: imageData,
            fileURLs: fileURLs
        )
        Self.captureQueue.async { Self.capture(request) }
    }

    private nonisolated static func capture(_ request: ClipCaptureRequest) {
        if !request.fileURLs.isEmpty {
            captureImageFile(request: request)
            return
        }
        let hasImage = request.imageData != nil
        if let text = request.text {
            let classified = ClipClassifier.classify(text)
            let imageWithURL = hasImage && (classified?.kind == .link
                || text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty)
            if !imageWithURL {
                guard let classified else { return }
                switch classified.kind {
                case .text where !request.captureText: return
                case .link where !request.captureLinks: return
                default: break
                }
                let hash = ClipImageProcessor.textHash(classified.content)
                let source = request.source
                Task { @MainActor in ClipStore.shared.addText(classified, hash: hash, source: source) }
                return
            }
        }
        guard request.captureImages, let data = request.imageData else { return }
        process(data, source: request.source)
    }

    private nonisolated static func captureImageFile(request: ClipCaptureRequest) {
        guard request.captureImages, request.fileURLs.count == 1, let url = request.fileURLs.first,
              let type = UTType(filenameExtension: url.pathExtension), type.conforms(to: .image),
              let size = (try? url.resourceValues(forKeys: [.fileSizeKey]))?.fileSize,
              size <= ClipImageProcessor.maximumBytes,
              let data = try? Data(contentsOf: url) else { return }
        process(data, source: request.source)
    }

    private nonisolated static func process(_ data: Data, source: String?) {
        guard data.count <= ClipImageProcessor.maximumBytes,
              let prepared = ClipImageProcessor.prepare(data) else { return }
        Task { @MainActor in _ = await ClipStore.shared.addImage(prepared, source: source) }
    }
}
